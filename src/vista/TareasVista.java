    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String nombre = txtNombre.getText();
        String descripcion = txaDescripcion.getText();
        
        try{
            if(txtId.getText().trim().isEmpty()){
                tareaControlador = new TareaControlador();
                tareaControlador.crearTarea(nombre, descripcion);
                JOptionPane.showMessageDialog(null,
                                    "Tarea guardada satisfactoriamente",
                                    "Datos Guardados",
                                    JOptionPane.OK_OPTION);
                limpiar();
                limpiar2();
                cargarTareasEnTabla();
            }else{
                //Actualizar la tarea existente
                int id = Integer.parseInt(txtId.getText().trim());
                tareaControlador = new TareaControlador();
                tareaControlador.actualizarTarea(id, nombre, descripcion, true);
                JOptionPane.showMessageDialog(null, 
                                "Tarea editada satisfactoriamente", 
                                "Datos Editados", 
                                JOptionPane.OK_OPTION);
                limpiar();
                limpiar2();
                cargarTareasEnTabla();
            }
        
        }catch(NumberFormatException ex){
           JOptionPane.showMessageDialog(null,
                                        "El ID debe ser un número válido.", 
                                        "Error", 
                                        JOptionPane.ERROR_MESSAGE); 
        }
        catch(Exception ex){
            JOptionPane.showMessageDialog(null,
                                            "Error en: " + ex.getMessage(), 
                                            "Error", 
                                            JOptionPane.ERROR_MESSAGE);
        }
            
            
            
            
       
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnBuscarTareaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarTareaActionPerformed
        try{
            int id = Integer.parseInt(txtId.getText());
            
            //Llamamos al controlador para buscar si la tarea existe o no
            Tarea tarea = tareaControlador.buscarTareaPorId(id);
        
            //Vamos a preguntar si esta la tarea
            if(tarea != null){
                txtNombre.setText(tarea.getNombre());
                txaDescripcion.setText(tarea.getDescripcion());
            }else{
                JOptionPane.showMessageDialog(
                        this,
                        "No hay tareas por ese ID, intentelo nuevamente",
                        "Error",
                        JOptionPane.ERROR_MESSAGE);
            }
            
        }catch(NumberFormatException ex){
            JOptionPane.showMessageDialog(
                    null,
                    "Error, solo permite numeros",
                    "Error",JOptionPane.ERROR_MESSAGE);
            limpiar();
            limpiar2();
        }
    }//GEN-LAST:event_btnBuscarTareaActionPerformed

    private void btnCargarTareasActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarTareasActionPerformed
        cargarTareasEnTabla();
    }//GEN-LAST:event_btnCargarTareasActionPerformed

    private void limpiar(){
        txtNombre.setText("");
        txaDescripcion.setText("");
    }
    
    private void limpiar2(){
        txtId.setText("");
    }
    
    private void cargarTareasEnTabla(){
        try{
        
            //Primero obtenemos la lista de las tareas desde el controlador
            List<Tarea> tareas = tareaControlador.listarTareas();
            
            //Obtenemos el modelo de la tabla
            DefaultTableModel modelo = (DefaultTableModel) tblTareas.getModel();
            
            //Limpiar el modelo
            modelo.setRowCount(0);
            
            //Vamos a agregar las filas con los datos de las tareas
            for(Tarea tarea : tareas){
                Object[] fila = {
                    tarea.getId(),
                    tarea.getNombre(),
                    tarea.getDescripcion(),
                    tarea.getEstado() ? "Activa" : "Inactiva"
                };
                modelo.addRow(fila);
            }
            
        }catch(Exception ex){
            System.out.println("Error al cargas tareas" + ex.getMessage());
            ex.printStackTrace();
        }
    }
    
    
    
    
